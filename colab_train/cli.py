def cmd_list(args) -> int:
    print("presets (built in):")
    for n in spec.preset_names():
        print(f"  {n}")
    jobs = sorted(Path.cwd().joinpath("jobs").glob("*.yaml")) if Path("jobs").is_dir() else []
