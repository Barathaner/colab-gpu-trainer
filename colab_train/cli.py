def _available_jobs() -> list[str]:
    """Job names that validate: jobs/*.yaml in the cwd first, then the built-in presets."""
    names: list[str] = []
    local = sorted(p.stem for p in Path("jobs").glob("*.yaml")) if Path("jobs").is_dir() else []
    for n in local + spec.preset_names():
        if n in names:
            continue
        try:
            spec.load(spec.resolve_job_arg(n))
        except SpecError:
            continue
        names.append(n)
    return names


def _used_run_ids(job: dict) -> set[str]:
    used = {str(v["run_id"]) for v in _state().values() if isinstance(v, dict) and v.get("run_id")}
    try:
        used |= set(wandb_names(job))
    except Exception as e:  # W&B unreachable: pick from the local state only, and say so
        print(f"note: could not list W&B runs ({type(e).__name__}); the run name is checked against local state only")
    return used


def wandb_names(job: dict) -> list[str]:
    from . import wandb_status
    return wandb_status.run_names(job)


def _pick_job(args, cfg: dict) -> dict:
    avail = _available_jobs()
    if args.auto or not sys.stdin.isatty():
        name, why = pick.choose_auto(avail, browser.auto_jobs(cfg))
    else:
        name, why = pick.choose_interactive(avail), "chosen by you"
    base = _load(name)
    prefix = base["run"]["prefix"] or base["name"]
    run_name = args.run_name or pick.fresh_run_name(prefix, base["run"]["name"], _used_run_ids(base))
    job = _load(name, run_name)
    print(f"chose {name} ({why}); new run {job['derived']['run_id']}")
    return job


def _guard_one_runtime(job: dict, force: bool) -> str | None:
    """Refuse a second runtime: another job's browser run, this job's run, or a running W&B run. None = go."""
    if force:
        return None
    state = _state()
    name = job["name"]
    others = [k for k, v in state.items() if k != name and isinstance(v, dict) and v.get("browser_running")]
    limit = worker.settings(browser.load_config())["max_parallel"]
    if len(others) >= limit:
        return (f"{len(others)} browser runtime(s) recorded ({', '.join(others)}), max_parallel is {limit}. "
                f"Stop one first (colab-train stop JOB --browser) or raise max_parallel in .colab-train/config.json")
    if others:
        print(f"note: {', '.join(others)} also has a runtime; running in parallel (max_parallel {limit})")
    if state.get(name, {}).get("browser_running"):
        return f"{name} already has a browser runtime recorded. Stop it first or pass --force"
    if job["wandb"]["mode"] == "disabled":
        return None
    try:
        from . import wandb_status
        run = wandb_status.find_run(job)
    except Exception as e:  # noqa: BLE001 - any W&B failure: refuse rather than risk a second runtime
        return f"could not check W&B for a running run ({type(e).__name__}); pass --force if you are sure"
    if run is not None and run.state == "running":
        return f"W&B run {run.name} is already running. Do not start a second runtime; pass --force to override"
    return None


def _launch_browser(args) -> int:
    try:
        browser.require_playwright()
        cfg = browser.load_config()
        job = _pick_job(args, cfg) if not args.job else _load(args.job, args.run_name)
        refusal = _guard_one_runtime(job, getattr(args, "force", False))
        if refusal:
            print(f"refused: {refusal}", file=sys.stderr)
            return 3
        gone = secrets.missing(_needed_secrets(job))
        if gone:
            _print_missing_secrets(gone)
            return 3
        d = job["derived"]
        nb = render.write_notebook(job, _notebook_path(job, args.out)).resolve()
        print(f"job {job['name']}  run {d['run_id']}  notebook {nb}")
        return _drive_launch(job, nb, args.job or job["name"])
    except colab_web.SafetyStop as e:
        print(f"STOP: {e.reason}. Nothing was clicked past it. A human has to look at the browser window.")
        if e.screenshot:
            print(f"screenshot: {e.screenshot}")
        return 3
    except SpecError as e:
        for err in e.errors:
            print(f"error: {err}", file=sys.stderr)
        return 2
    except browser.BrowserError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1


def _drop_refused(name: str, ctx, page) -> None:
    """Colab refused this job's runtime: the other sessions keep running. Bring their tabs back to the front and
    close this new one. This job never got a runtime, so it must not count against max_parallel."""
    state = _state()
    if name in state:
        state[name]["browser_running"] = False
        _save_state(state)
    _focus_running_tabs(ctx)
    try:
        page.close()
    except Exception:  # noqa: BLE001 - closing is best effort
        pass


def _drive_launch(job: dict, nb: Path, ref: str | None = None) -> int:
    """Open, set up and run the job's notebook in Colab. ref: the job argument that finds this job again."""
    ref = ref or job["name"]
    name = job["name"]
    with browser.cdp_context() as ctx:
        home = colab_web.open_home(ctx)
        if browser.login_state(home) == "logged_out":
            shot = browser.screenshot(home, "not-logged-in")
            raise browser.SafetyStop("not signed in to Google in the dedicated browser "
                                     "(run `colab-train browser setup`, then sign in yourself)", shot)
        page = home
        try:
            page = colab_web.upload_notebook(home, nb)
            browser.screenshot(page, "uploaded")
            browser.check_safety(page)
            rt = job.get("runtime") or {}
            accel = (colab_web.ensure_t4(page, rt.get("gpu_type", "T4"))
                     if rt.get("accelerator", "GPU") == "GPU" else "CPU runtime (runtime.accelerator: none)")
            browser.screenshot(page, "runtime-t4")
            print(f"runtime type: {accel}")
            # Secrets panel: no screenshot while it is open (secrets_panel raises PanelError with text only)
            done = secrets_panel.ensure_secrets(page, _needed_secrets(job), log=lambda _m: None)
            for n, what in done.items():
                print(f"secret {n}: {what}")
            # Record the run before Run all so a failure below still leaves the guard and stop working.
            state = _state()
            state[name] = {**state.get(name, {}), "run_id": job["derived"]["run_id"],
                           "run_name": job["run"]["name"], "notebook": str(nb), "browser_running": True,
                           "browser": {"url": page.url, "accelerator": accel,
                                       "launched": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")}}
            _save_state(state)
            try:
                lines = colab_web.run_all(page, log=print)
            except colab_web.RunnerStuck as e:
                # Fallback, once: the runner printed nothing. Keep a screenshot, disconnect, Run all again.
                browser.screenshot(page, "runner-stuck")
                print(f"runner stuck ({e}). Retrying once: disconnect and Run all again.")
                colab_web.disconnect_and_delete(page)
                lines = colab_web.run_all(page, log=print)
            browser.screenshot(page, "run-all")
        except colab_web.SessionLimit:
            _drop_refused(name, ctx, page)
            raise
        except (browser.SafetyStop, secrets_panel.PanelError):
            raise
        except Exception as e:  # noqa: BLE001 - keep a screenshot of whatever went wrong, then report it
            if colab_web.session_limit(page):  # the dialog can open at any step (Connect too), not only at Run all
                dismissed = colab_web.dismiss_session_limit(page)
                shot = browser.screenshot(page, "too-many-sessions")
                _drop_refused(name, ctx, page)
                raise colab_web.SessionLimit(colab_web.SESSION_LIMIT_REASON
                                             + (" (Cancel clicked)" if dismissed else ""), shot) from e
            shot = browser.screenshot(page, "failure")
            raise browser.BrowserError(f"{type(e).__name__}: {e}" + (f" (screenshot: {shot})" if shot else "")) from e
        state = _state()
        state[name]["browser"]["url"] = page.url
        _save_state(state)
    print("runner output (first lines):")
    for line in lines[:12]:
        print("  " + line)
    if not any(ln.startswith("[colab-train] GPU:") for ln in lines):
        print("GPU line not seen yet; `colab-train status`/`logs` will show it once the run starts")
    print(f"next: colab-train status {ref}   (stop: colab-train stop {ref} --browser)")
    return 0


def _focus_running_tabs(ctx) -> None:
    for name, entry in _state().items():
        if isinstance(entry, dict) and entry.get("browser_running"):
            tab = colab_web.find_job_page(ctx, (entry.get("browser") or {}).get("url"),
                                          Path(entry.get("notebook", "")).stem)
            if tab is not None:
                tab.bring_to_front()
                print(f"focused the running job's tab: {name}")


def _stop_browser(args) -> int:
    job = _load(args.job, args.run_name)
    name = job["name"]
    state = _state()
    entry = state.get(name, {})
    if not entry.get("browser_running"):
        print(f"no browser runtime recorded for {name}; nothing to stop. If one is still on, use "
              "Runtime > Disconnect and delete runtime in its tab.")
        return 0
    if not args.yes:
        if not sys.stdin.isatty():
            print("refused: pass --yes to disconnect a runtime without a terminal prompt", file=sys.stderr)
            return 1
        if input(f"Disconnect and delete the Colab runtime of {name} ({entry.get('run_id')})? [y/N] ").strip().lower() \
                not in ("y", "yes"):
            print("kept the runtime")
            return 1
    saved = entry.get("browser") or {}
    stem = Path(entry.get("notebook", "")).stem
    with browser.cdp_context() as ctx:
        page = colab_web.find_job_page(ctx, saved.get("url"), stem)
        if page is None:
            raise browser.BrowserError("no Colab tab for this run in the browser: close the runtime by hand")
        page.bring_to_front()
        browser.screenshot(page, "before-stop")
        gone = colab_web.disconnect_and_delete(page)
        browser.screenshot(page, "after-stop")
    entry["browser_running"] = False
    state[name] = entry
    _save_state(state)
    if gone:
        print(f"runtime of {name} disconnected and deleted")
    else:
        print("clicked Disconnect and delete runtime, but no Connect or Reconnect button came back in 60 s: check the screenshot")
    return 0


