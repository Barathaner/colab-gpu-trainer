def _needed_secrets(job: dict) -> list[str]:
    return [secret for _, secret in render.secret_names(job)]


def _print_missing_secrets(gone: list[str]) -> None:
    for n in gone:
        print(f"missing secret value: {n} (no local value). Set it in a terminal, by hand (hidden input):")
        print(f"  colab-train secrets set {n}")
    print("or import from an existing source: colab-train secrets import   (see `colab-train secrets --help`)")


def _job_tab(ctx: Any, home: Any, job: dict) -> Any:
    """The job's notebook tab: the one launch recorded, else a fresh upload of the rendered notebook."""
    st = _state().get(job["name"], {})
    saved = (st.get("browser") or {}).get("url")
    page = colab_web.find_job_page(ctx, saved, Path(st.get("notebook", "")).stem) if st else None
    if page is not None:
        return page
    nb = render.write_notebook(job, _notebook_path(job, None)).resolve()
    page = colab_web.upload_notebook(home, nb)
    state = _state()
    state[job["name"]] = {**state.get(job["name"], {}), "notebook": str(nb),
                          "browser": {"url": page.url, "launched": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")}}
    _save_state(state)
    return page


def cmd_browser_setup(args) -> int:
    job = None
    needed: list[str] = []
    if args.job:
        job = _load(args.job)
        needed = _needed_secrets(job)
        gone = secrets.missing(needed)
        if gone:
            _print_missing_secrets(gone)
            return 1
    with browser.cdp_context() as ctx:
        page = colab_web.open_home(ctx)
        print("A Colab tab is open in the dedicated browser. Now, by hand, in that window:")
        print("  1. Sign in to your Google account. Type the password and any 2FA code only there.")
        if job is not None:
            print("  2. Nothing else: this tool fills the Secrets panel from the local store (names: "
                  + ", ".join(needed) + ").")
        if args.check:
            ls = browser.login_state(page)
            print("ok: signed in" if ls == "logged_in" else f"not signed in yet (state: {ls})")
            return 0 if ls == "logged_in" else 1
        print(f"waiting up to {args.timeout} s for the sign-in ...")
        deadline = time.monotonic() + args.timeout
        ls = "unknown"
        while True:
            ls = browser.login_state(page)
            if ls == "logged_in":
                break
            if time.monotonic() > deadline:
                browser.screenshot(page, "not-signed-in")
                print(f"not signed in (state: {ls}). Run setup again after signing in.")
                return 1
            page.wait_for_timeout(3000)
        print("ok: signed in")
        if job is None:
            browser.screenshot(page, "signed-in")
            print("Next: colab-train launch --browser JOB")
            return 0
        try:
            tab = _job_tab(ctx, page, job)
            tab.bring_to_front()
            done = secrets_panel.ensure_secrets(tab, needed, update=args.update, log=lambda _m: None)
        except secrets_panel.PanelError as e:  # text only: no screenshot while the panel may be open
            print(f"secrets: {e}")
            return 1
        for n, what in done.items():
            print(f"secret {n}: {what}")
        browser.screenshot(tab, "secrets-done")  # the panel is closed by now
        print("ok: secrets set in Colab. Next: colab-train launch --browser " + job["name"])
        return 0


