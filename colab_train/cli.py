STATE_DIR = Path(".colab-train")
STATE_FILE = STATE_DIR / "state.json"


def _state() -> dict:
    try:
        return json.loads(STATE_FILE.read_text())
    except (OSError, ValueError):
        return {}


def _save_state(state: dict) -> None:
    STATE_DIR.mkdir(exist_ok=True)
    STATE_FILE.write_text(json.dumps(state, indent=2, sort_keys=True) + "\n")


def _load(arg: str, run_name: str | None = None) -> dict:
    path = spec.resolve_job_arg(arg)
    return spec.load(path, run_name=run_name)


def _wandb_creds_hint() -> str | None:
    import os
    if os.environ.get("WANDB_API_KEY") or (Path.home() / ".netrc").exists():
        return None
    return "no W&B key found (WANDB_API_KEY or ~/.netrc); status and the notebook need one"


