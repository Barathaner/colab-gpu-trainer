def cmd_secrets_set(args) -> int:
    secrets.check_name(args.name)
    if sys.stdin.isatty():
        value = getpass.getpass(f"value for {args.name} (hidden, not shown or logged): ")
    else:
        value = sys.stdin.readline().rstrip("\n")  # piped input; still never echoed
    backend = secrets.set_value(args.name, value, source="set")
    print(f"stored {args.name} ({backend}). The value is not shown.")
    return 0


def cmd_secrets_import(args) -> int:
    if args.from_file:
        if not args.name:
            print("error: --from-file needs --name NAME", file=sys.stderr)
            return 2
        src = secrets.import_file(Path(args.from_file), args.name)
        print(f"{args.name}: imported from {src}. The value is not shown.")
    elif args.git_host:
        if not args.name:
            print("error: --git-host needs --name NAME", file=sys.stderr)
            return 2
        src = secrets.import_git_credential(args.git_host, args.name)
        print(f"{args.name}: imported from {src}. The value is not shown.")
    else:
        src = secrets.import_wandb()
        print(f"WANDB_API_KEY: imported from {src}. The value is not shown.")
    return 0


