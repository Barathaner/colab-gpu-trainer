"""colab-train: SkyPilot-style CLI for training jobs on a free Google Colab GPU.

  colab-train list                       presets and jobs/*.yaml
  colab-train init  [NAME] [--repo URL --train CMD ...]  write jobs/<name>.yaml (asks if run in a terminal)
  colab-train doctor [JOB ...] [--no-network]  check Python, Chrome, secret names, job files, repo URL
  colab-train validate JOB               check the spec, print the resolved train command
  colab-train render JOB [--out F]       write a ready-to-run .ipynb (secret NAMES only)
  colab-train launch JOB [--publish auto|gist|local] [--run-name N]
  colab-train launch [JOB] --browser [--auto] [--force]   drive your Chrome: upload, T4, Run all
  colab-train browser start | status | setup [JOB]     the dedicated browser (start in a desktop terminal)
  colab-train secrets set NAME | import | list | rm NAME  local values for the Colab Secrets (never shown)
  colab-train status JOB [--json]        run state, iteration, speed, ETA, videos (W&B)
  colab-train logs JOB [--lines N]       tail of the run's output.log (W&B)
  colab-train resume JOB                 say whether to resume, and where the notebook is
  colab-train stop JOB [--browser] [--yes]  without --browser: print the manual steps

JOB is a path to a YAML file, jobs/<name>.yaml, or a built-in preset name (see `list`).
State lives in ./.colab-train/ (notebooks and state.json). It holds no secret values.
"""
