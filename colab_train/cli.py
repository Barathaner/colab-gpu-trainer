def cmd_submit(args) -> int:
    path = spec.resolve_job_arg(args.job)
    job = spec.load(path, run_name=args.run_name)  # validate now, not when the worker gets to it
    item = cq.add(str(path.resolve()), args.run_name or job["run"]["name"], args.priority, args.notify_pane,
                  str(Path.cwd()), name=job["name"])
    print(f"queued {item['id']}: {job['name']} run {args.run_name or job['run']['name']} "
          f"(priority {item['priority']}). The worker launches it when a slot is free.")
    return 0


def _fmt_eta(h) -> str:
    return f"{h} h" if h is not None else "-"


def cmd_queue(args) -> int:
    data = cq.snapshot()
    items = data["items"]
    if args.json:
        print(json.dumps(data, indent=2))
        return 0
    if data.get("blocked_until"):
        print(f"queue blocked until {data['blocked_until']} (usage limit or no GPU)")
    if not items:
        print("queue is empty. Submit one: colab-train submit JOB")
        return 0
    print(f"{'id':<9}{'status':<13}{'pri':>4}  {'job':<22}{'run':<22}{'iter':>9}  {'s/it':>6}  {'ETA':>8}  W&B")
    for it in items:
        it_txt = f"{it.get('iter') if it.get('iter') is not None else '-'}/{it.get('max_iters') or '-'}"
        sit = f"{it['sec_it']:.1f}" if it.get("sec_it") else "-"
        print(f"{it['id']:<9}{it['status']:<13}{it['priority']:>4}  {it.get('name', it['job'])[:21]:<22}"
              f"{(it.get('run_name') or '-')[:21]:<22}{it_txt:>9}  {sit:>6}  {_fmt_eta(it.get('eta_h')):>8}  "
              f"{it.get('wandb_url') or '-'}")
        if it.get("reason") and it["status"] not in ("running", "finished"):
            print(f"{'':<9}  {it['reason'][:110]}")
    return 0


def cmd_cancel(args) -> int:
    prev, item = cq.cancel(args.id)
    if prev == "missing":
        print(f"no queue item {args.id}", file=sys.stderr)
        return 1
    if prev in ("running", "stalled", "launching"):  # launching: a worker stopped mid-launch can leave a runtime
        if not args.yes:
            if not sys.stdin.isatty() or input(f"Stop the running Colab job {item['job']} ({args.id})? [y/N] ").strip().lower() \
                    not in ("y", "yes"):
                print("kept it running")
                return 1
        cwd = os.getcwd()
        try:
            if item.get("workdir"):
                os.chdir(item["workdir"])
            _stop_browser(argparse.Namespace(job=item["job"], run_name=item.get("run_name"), yes=True))
        finally:
            os.chdir(cwd)

        def _mark(data: dict) -> None:
            it = cq.find(data, args.id)
            if it:
                it["status"], it["reason"] = "cancelled", "cancelled by the user"

        cq.update(_mark)
        print(f"cancelled {args.id}: the running Colab runtime was stopped")
        return 0
    print(f"cancelled {args.id} ({prev} -> cancelled)" if prev == "queued" else f"{args.id} was {prev}; nothing to do")
    return 0


def cmd_worker(args) -> int:
    cfg = browser.load_config()
    st = worker.settings(cfg)
    interval = args.interval if args.interval is not None else st["interval_s"]
    print(f"worker: every {interval:g} s, max_parallel {st['max_parallel']}, stall {st['stall_min']:g} min, "
          f"max_resumes {st['max_resumes']}, backoff {st['backoff_h']:g} h. Ctrl+C to stop.", flush=True)
    env = worker.pythonpath_env()
    try:
        worker.loop(st, interval, launcher=lambda item: worker.launch_child(item, env), once=args.once)
    except KeyboardInterrupt:
        print("worker stopped")
    return 0


def cmd_browser(args) -> int:
    return args.browser_fn(args)


