def _ls_remote(job: dict, token: str | None, *refs: str) -> tuple[int, str, str]:
    """`git ls-remote --symref <url> REFS`: one read, no clone. The token goes through an env var, never argv."""
    url = job["repo"]["url"]
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0"}
    if token:
        env["COLAB_TRAIN_GIT_TOKEN"] = token
    cmd = [*runner.git_prefix(job, "primary", host=urlparse(url).hostname), "ls-remote", "--symref", url, *refs]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, env=env, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as e:
        return 1, "", f"could not run git ({type(e).__name__})"
    return r.returncode, r.stdout, r.stderr


def _default_branch(stdout: str) -> str | None:
    """The branch HEAD points to, from `ls-remote --symref` output ("ref: refs/heads/master\tHEAD")."""
    m = re.search(r"^ref: refs/heads/(\S+)\s+HEAD$", stdout, re.M)
    return m.group(1) if m else None


def _remote_default_branch(url: str) -> str | None:
    """Default branch of a repo reachable without a token (public), or None."""
    job = {"repo": {"url": url, "token_user": "x-access-token"}}
    try:
        rc, out, _err = _ls_remote(job, None, "HEAD")
    except Exception:  # noqa: BLE001 - only a default for a question
        return None
    return _default_branch(out) if rc == 0 else None


def _repo_reachable(job: dict, token: str | None) -> tuple[bool, str]:
    """The repo answers and job.repo.branch exists on it."""
    branch = job["repo"].get("branch")
    rc, out, err = _ls_remote(job, token, "HEAD", *([f"refs/heads/{branch}"] if branch else []))
    if rc != 0:
        msg = err.strip().splitlines()[-1] if err.strip() else "git failed"
        return False, secrets.scrub(msg, [token])[:200]
    if branch and not re.search(rf"\srefs/heads/{re.escape(branch)}$", out, re.M):
        default = _default_branch(out)
        return False, (f"branch {branch!r} not found" + (f"; the default branch is {default!r}, "
                                                          f"set repo.branch: {default}" if default else ""))
    want = f"refs/heads/{branch}" if branch else "HEAD"
    sha = next((line.split()[0][:8] for line in out.splitlines()
                if not line.startswith("ref:") and line.split()[-1:] == [want]), "")
    return True, (f"{branch or 'HEAD'} {sha}" if sha else "reachable")


def cmd_doctor(args) -> int:
    fails = 0

    def row(level: str, label: str, detail: str = "", fix: str = "") -> None:
        nonlocal fails
        fails += level == "FAIL"
        print(f"[{level:<4}] {label}" + (f": {detail}" if detail else ""))
        if fix and level != "ok":
            print(f"        fix: {fix}")

    row("ok" if sys.version_info >= (3, 10) else "FAIL", f"python {sys.version.split()[0]}",
        fix="" if sys.version_info >= (3, 10) else "install Python 3.10 or newer")
    try:
        import yaml  # noqa: F401
        row("ok", "pyyaml installed")
    except ImportError:
        row("FAIL", "pyyaml missing", fix="pip install pyyaml (or reinstall colab-train)")
    from . import wandb_status
    if wandb_status.installed():
        row("ok", "wandb installed (optional)")
    else:
        row("warn", "wandb not installed (optional)", "fine when W&B is off", wandb_status.INSTALL_HINT)
    try:
        import playwright  # noqa: F401
        row("ok", "playwright installed (for --browser only)")
    except ImportError:
        row("warn", "playwright not installed (for --browser only)", "CLI-only use does not need it",
            "pip install 'colab-train[browser]'")
    try:
        row("ok", "Chrome found", browser.find_browser(browser.load_config()))
    except browser.BrowserError as e:
        row("warn", "no Chrome or Brave found (for --browser only)", str(e).split(".")[0],
            "install Google Chrome, or set COLAB_TRAIN_BROWSER to its path")
    if browser.PROFILE_DIR.is_dir():
        row("ok", "dedicated browser profile exists", str(browser.PROFILE_DIR), "")
    else:
        row("warn", "dedicated browser profile not created yet", str(browser.PROFILE_DIR),
            "colab-train browser setup (once, in a desktop terminal; sign in to Google yourself)")
    try:
        names = sorted(secrets.names())
        row("ok", "local secret store readable", f"{len(names)} name(s): {', '.join(names) or 'none'}")
    except secrets.SecretsError as e:
        row("FAIL", "local secret store", str(e), "check ~/.config/colab-train/ permissions")
        names = []

    targets = [Path(p) for p in args.jobs] if args.jobs else sorted(Path("jobs").glob("*.yaml")) \
        if Path("jobs").is_dir() else []
    if not targets:
        row("warn", "no job files", "none given and no ./jobs/*.yaml", "colab-train init")
    for path in targets:
        print(f"-- job {path}")
        try:
            job = spec.load(path, run_name=args.run_name)
        except (SpecError, OSError) as e:
            for err in getattr(e, "errors", [str(e)]):
                row("FAIL", "job spec", err)
            continue
        row("ok", "job spec valid", f"{job['name']} (run {job['derived']['run_id']})")
        token_names = [n for n in (job["repo"].get("token_secret"), job["repo"].get("fallback_token_secret")) if n]
        wb_names = ["WANDB_API_KEY"] if job["wandb"]["mode"] == "online" else []
        for name in dict.fromkeys(token_names + wb_names + [s for s in job["secret_env"].values()]):
            if os.environ.get(name) or secrets.get(name) is not None:
                row("ok", f"secret {name} set locally")
            else:
                row("warn", f"secret {name} not set locally", "fine if it is in Colab Secrets already",
                    f"colab-train secrets set {name}   (or add {name} in Colab Secrets, Notebook access ON)")
        if job["wandb"]["mode"] == "online" and not wandb_status.installed():
            row("FAIL", "wandb not installed", "this job logs to W&B; status, logs and the worker need it",
                wandb_status.INSTALL_HINT)
        if job["wandb"]["mode"] == "online" and not (os.environ.get("WANDB_API_KEY")
                                                       or (Path.home() / ".netrc").exists()):
            row("warn", "no W&B login here", "needed only for `status`/`logs` and the W&B resume",
                "colab-train secrets import (reads W&B from env or ~/.netrc, value never printed)")
        if args.no_network:
            row("warn", f"repo {job['repo']['url']}", "not checked (--no-network)")
            continue
        token = secrets.get(job["repo"]["token_secret"]) if job["repo"].get("token_secret") else None
        if job["repo"].get("token_secret") and token is None and not os.environ.get(job["repo"]["token_secret"]):
            row("warn", "git token not set locally", job["repo"]["token_secret"], "colab-train secrets set "
                + job["repo"]["token_secret"])
        ok, detail = _repo_reachable(job, token)
        if ok:
            row("ok", f"repo reachable: {job['repo']['url']}", detail)
        else:
            fix = (f"the token in {job['repo']['token_secret']} may be wrong, expired or lack read access to this "
                   "repo (a fine-grained GitHub token reads only the repos listed under its Repository access; add "
                   f"this one there); for a new token value: colab-train secrets set {job['repo']['token_secret']}"
                   if job["repo"].get("token_secret")
                   else "check the URL in a browser; a private repo needs repo.token_secret")
            row("FAIL", f"repo not reachable: {job['repo']['url']}", detail, fix)
    print("doctor: " + ("problems found (see FAIL above)" if fails else "no blocking problems"))
    return 1 if fails else 0


def cmd_validate(args) -> int:
    job = _load(args.job, args.run_name)
    d = job["derived"]
    wb_label = f"W&B {d['wandb_entity']}/{d['wandb_project']}" if job["wandb"]["mode"] != "disabled" else "no W&B"
    print(f"ok: {job['name']}  run {d['run_id']}  {wb_label}")
    print(f"repo: {job['repo']['url']} @ {job['repo']['branch']}  token secret: "
          f"{job['repo']['token_secret'] or '(none, public)'}")
    print(f"resume: {job['resume']['source']}  budget: {job['limits']['max_hours']} h  "
          f"videos every {job['video']['every']} it")
    repo = Path(args.workdir) / d["repo_dir_name"]
    for c in runner.build_install_commands(job, repo):
        print("install: " + " ".join(c))
    print("train (fresh start): " + " ".join(runner.build_train_command(job, repo, None)))
    if job["bench"].get("command"):
        print("bench (template, filled in after training): " + job["bench"]["command"])
    hint = _wandb_creds_hint()
    if hint:
        print("note: " + hint)
    return 0


def _notebook_path(job: dict, out: str | None) -> Path:
    if out:
        return Path(out)
    return STATE_DIR / "notebooks" / f"{job['name']}-{job['derived']['run_id']}.ipynb"


def cmd_render(args) -> int:
    job = _load(args.job, args.run_name)
    path = render.write_notebook(job, _notebook_path(job, args.out))
    print(f"wrote {path.resolve()}")
    print("open it in Colab: File > Upload notebook (or publish with `colab-train launch`)")
    return 0


def _accel_label(job: dict) -> str:
    rt = job.get("runtime") or {}
    return "no GPU (CPU runtime)" if rt.get("accelerator", "GPU") == "none" else f"{rt.get('gpu_type', 'T4')} GPU"


def _steps(job: dict, nb_path: Path, colab_url: str | None) -> list[str]:
    names = ", ".join(f"`{s}`" for _, s in render.secret_names(job))
    lines = [
        "Colab steps (about 1 minute the first time):",
    ]
    if colab_url:
        lines.append(f"  1. open {colab_url}")
    else:
        lines.append("  1. open https://colab.research.google.com/#create=true and choose Upload, "
                     f"then pick {nb_path.resolve()}")
    lines += [
        ("  2. Runtime > Change runtime type: " + _accel_label(job) + " (set in the notebook; check it)"),
        f"  3. Secrets (key icon, Notebook access ON): {names}" if names else "  3. Secrets: none needed",
        "  4. Runtime > Run all. Keep the tab open; reconnect and Run all again if it drops.",
        f"  5. Follow it here: colab-train status {job['name']}   (or logs / resume)" if job["wandb"]["mode"] != "disabled"
        else "  5. Follow it in the Colab tab (W&B is off; `colab-train status` reads the tab only in --browser mode)",
    ]
    return lines


def cmd_launch(args) -> int:
    if getattr(args, "browser", False):
        return _launch_browser(args)
    if not args.job:
        print("error: JOB is required (or use --browser to pick one)", file=sys.stderr)
        return 2
    job = _load(args.job, args.run_name)
    d = job["derived"]
    nb = render.write_notebook(job, _notebook_path(job, args.out))
    desc = f"colab-train {job['name']} {d['run_id']}"
    try:
        pub = publish.publish(nb.resolve(), args.publish, desc)
    except publish.PublishError as e:
        print(f"publish failed: {e}", file=sys.stderr)
        return 1
    state = _state()
    state[job["name"]] = {
        "run_id": d["run_id"], "run_name": job["run"]["name"], "notebook": str(nb.resolve()),
        "colab_url": pub["colab_url"], "gist_url": pub["gist_url"],
        "launched": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
    }
    _save_state(state)
    wb = f"W&B {d['wandb_entity']}/{d['wandb_project']}" if job["wandb"]["mode"] != "disabled" else "no W&B"
    print(f"job {job['name']}  run {d['run_id']}  {wb}")
    print(f"notebook: {nb.resolve()}")
    if pub["colab_url"]:
        print(f"one-click URL: {pub['colab_url']}")
    else:
        print("published: no (local file only; gh not logged in or --publish local)")
    for line in _steps(job, nb, pub["colab_url"]):
        print(line)
    hint = _wandb_creds_hint()
    if hint:
        print("note: " + hint)
    print("automation limit: the Run all click and the Secrets setup are manual on Colab (see docs/AI_USAGE.md).")
    return 0


def _status_text(s: dict) -> str:
    it = s["iteration"]
    lines = [
        f"run     {s['run']}  state={s['state']}",
        f"url     {s['url']}",
        f"iter    {it if it is not None else '-'} / {s['max_iters']}",
        f"speed   {('%.1f s/iter' % s['sec_per_iter']) if s['sec_per_iter'] else 'n/a yet'}"
        + (f"  ETA ~{s['eta_hours']} h (running)" if s["eta_hours"] is not None else ""),
        f"ckpts   {s['checkpoints']} on W&B, newest {s['newest_checkpoint']}",
        f"videos  {s['videos']}" + (f", latest {s['latest_video']}" if s["latest_video"] else
                                    ("" if not s["video_logged"] else " (logged in W&B summary)")),
        f"wall    {s['runtime_h']} h of run runtime",
    ]
    return "\n".join(lines)


